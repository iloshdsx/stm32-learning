#include <stdio.h>

/* 返回数组的最大值；同时把最大值的下标，通过 out_index 带出去
 *
 *   arr       : 数组首地址。const 表示"只读"，不许改数组内容
 *   len       : 数组里有几个数
 *   out_index : 出口参数，一个地址。下标要写进它指向的地方
 */
int max_index(const int *arr, int len, int *out_index)
{
    /* ---------- 准备阶段：先拿两个"筐子"装东西 ---------- */

    /* 中文：先假装第 0 个元素就是最大的
     * C  ：int max = arr[0];                        <-- 在这里敲这一行
     */

    /* 中文：下标也先记成 0
     * C  ：*out_index = 0;                          <-- 在这里敲这一行
     *      说明：这是"按门牌号上门，把 0 放进那个房间"
     */

    /* ---------- 计算阶段：一个一个往后比 ---------- */

    /* 中文：从第 1 个元素开始，一直看到最后一个
     * C  ：for (int i = 1; i < len; i++) {          <-- 在这里敲这一行
     *      为什么从 1 开始？因为第 0 个已经被当成初始最大值了
     */

        /* 中文：如果这个元素比我记的最大值还大
         * C  ：if (arr[i] > max) {                  <-- 在这里敲这一行
         */

            /* 中文：那就换成它，并且把它的位置 i 记下来
             * C  ：max = arr[i];                     <-- 在这里敲这一行
             * C  ：*out_index = i;                   <-- 在这里敲这一行
             */

        /* 中文：判断结束
         * C  ：}                                   <-- 在这里敲这一行
         */

    /* 中文：循环结束
     * C  ：}                                       <-- 在这里敲这一行
     */

    /* ---------- 交结果阶段 ---------- */

    /* 中文：把最大值交出去
     * C  ：return max;                              <-- 在这里敲这一行
     *      注意：改掉现在这句 return 0;
     */

    return 0;   /* <- 这一行要改成上面的 return max; */
}

