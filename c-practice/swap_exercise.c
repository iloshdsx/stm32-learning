#include <stdio.h>

/* ============================================================
 * 空 0（概念题，先不用写代码）：
 *   下面这个函数，能把 main 里的 x 和 y 换过来吗？跑之前先在纸上猜一猜。
 * ============================================================ */
void swap_by_value(int a, int b)
{
    int t = a;
    a = b;
    b = t;
}

/* ============================================================
 * 这个函数要通过"地址"来交换，需要你填 3 个空。
 *   提示：pa 是"指向 x 的指针"，*pa 才是"x 本人"
 * ============================================================ */
void swap_by_pointer(int *pa, int *pb)
{
    int t =*pa;      /* 空1：先把 pa 指的那个变量的值存起来 */
    *pa =*pb;       /* 空2：把 pb 指的值，写进 pa 指的地方 */
    *pb = t;       /* 空3：把暂存的值，写进 pb 指的地方 */
}

int main(void)
{
    int x = 1, y = 2;

    printf("初始状态：      x = %d, y = %d\n", x, y);

    swap_by_value(x, y);
    printf("传值版之后：    x = %d, y = %d\n", x, y);

    swap_by_pointer(&x,&y);   /* 空4、空5：调用时该怎么传参？ */
    printf("传地址版之后：  x = %d, y = %d\n", x, y);

    return 0;
}